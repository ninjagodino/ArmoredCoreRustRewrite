#!/usr/bin/env python3
"""Generate Xenia Canary ``.patch.toml`` files for the ACVD probe caves.

The patch DB (``src/xenia/patcher/patch_db.cc``) accepts ``be8/16/32/64``,
``f32/f64``, ``string``, ``u16string`` and ``array`` entries.  Each entry is a
table with ``address`` and ``value``; the file is selected by the module hash
and must be named ``^[A-Fa-f0-9]{8}.*\\.patch\\.toml$``.

Everything here is textual so the generated patch can be reviewed and tested
without launching Xenia.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field

from ppcgen import words_to_hex


@dataclass
class PatchSpec:
    title_name: str
    title_id: int
    module_hash: str
    name: str
    desc: str = "Generated by tools/xenia-probe."
    author: str = "acvd"
    be32: list[tuple[int, int]] = field(default_factory=list)
    arrays: list[tuple[int, bytes]] = field(default_factory=list)

    def add_be32(self, address: int, value: int) -> None:
        self.be32.append((address & 0xFFFFFFFF, value & 0xFFFFFFFF))

    def add_words(self, address: int, words: list[int]) -> None:
        self.arrays.append((address & 0xFFFFFFFF, bytes_from_words(words)))

    def add_bytes(self, address: int, data: bytes) -> None:
        self.arrays.append((address & 0xFFFFFFFF, data))


def bytes_from_words(words: list[int]) -> bytes:
    return b"".join(w.to_bytes(4, "big") for w in words)


def _toml_str(value: str) -> str:
    # JSON string escaping is a subset of TOML basic-string escaping.
    return json.dumps(value, ensure_ascii=False)


def _hex32(value: int) -> str:
    return f"0x{value & 0xFFFFFFFF:08X}"


def render_patch(spec: PatchSpec) -> str:
    lines = [
        f"title_name = {_toml_str(spec.title_name)}",
        f"title_id = \"{spec.title_id & 0xFFFFFFFF:08X}\"",
        f"hash = {_toml_str(spec.module_hash)}",
        "",
        "[[patch]]",
        f"name = {_toml_str(spec.name)}",
        f"desc = {_toml_str(spec.desc)}",
        f"author = {_toml_str(spec.author)}",
        "is_enabled = true",
        "",
    ]
    for address, value in spec.be32:
        lines += [
            "  [[patch.be32]]",
            f"  address = {_hex32(address)}",
            f"  value = {_hex32(value)}",
            "",
        ]
    for address, data in spec.arrays:
        lines += [
            "  [[patch.array]]",
            f"  address = {_hex32(address)}",
            f"  value = {_toml_str(data.hex())}",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def write_patch(path, spec: PatchSpec) -> str:
    text = render_patch(spec)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return text


def ring_prearm(spec: PatchSpec, ring: dict, offsets: dict, *, dump_ffx: bool,
                 warp_mode: int) -> None:
    """Write the AXPR header and zero the camera fields before game code runs.

    The ring lives in the zero-filled virtual tail of ``.data`` (Phase 0 read it
    at Title and Mission with 0 nonzero bytes and 0 indexed refs), so the patch
    DB can write it after LoadContinue without touching live game state.
    """
    base = int(ring["base"])
    cap = int(ring["cap"])
    recsz = int(ring["recsz"])
    spec.add_be32(base + int(offsets["write_index"]), 0)
    spec.add_be32(base + int(offsets["dropped"]), 0)
    spec.add_be32(base + int(offsets["magic"]), int(ring["magic"]))
    spec.add_be32(base + int(offsets["version"]), int(ring["version"]))
    spec.add_be32(base + int(offsets["flags"]),
                  int(ring["flags_dump_ffx"]) if dump_ffx else 0)
    # CAM_ENABLE .. CAM_READ_TARGET (0x14..0x4C) must start clean.
    for off in range(int(offsets["cam_enable"]), int(offsets["cam_read_target"]) + 12, 4):
        spec.add_be32(base + off, 0)
    spec.add_be32(base + int(offsets["cam_frame"]), 0)
    spec.add_be32(base + int(offsets["ring_cap"]), cap)
    spec.add_be32(base + int(offsets["ring_recsz"]), recsz)
    spec.add_be32(base + int(offsets["warp_mode"]), warp_mode & 0xFFFFFFFF)
    # Mapwarp evidence counters live in the unused header padding (0x60..0x68).
    for key in ("warp_calls", "warp_map", "warp_msb"):
        spec.add_be32(base + int(offsets[key]), 0)


def cave_patch(spec: PatchSpec, hook_addr: int, hook_word: int, cave_addr: int,
               cave_words: list[int], next_addr: int, *, return_mode: str = "branch") -> int:
    """Write the hook branch and the cave body.

    ``return_mode='branch'`` means the cave ends with ``b next_addr``;
    ``'blr'`` means the cave returns with the caller's LR and ``next_addr`` is
    ignored (the original instruction was a ``blr``).
    """
    from ppcgen import branch_word

    spec.add_be32(hook_addr, branch_word(hook_addr, cave_addr))
    spec.add_words(cave_addr, cave_words)
    return branch_word(hook_addr, cave_addr)


def mission_patch(spec: PatchSpec, getter_addr: int, getter_word: int, mission_id: int) -> None:
    if not 0 <= mission_id < 0x10000:
        raise ValueError(f"mission id out of range: {mission_id}")
    # 0x38600000 = li r3,<16-bit signed immediate>; the original is li r3,6000.
    opcode = getter_word & 0xFFFF0000
    if opcode != 0x38600000:
        raise ValueError(f"mission getter word is not li r3: 0x{getter_word:08X}")
    spec.add_be32(getter_addr, 0x38600000 | mission_id)
